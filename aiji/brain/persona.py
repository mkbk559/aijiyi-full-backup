def few_shot(name: str | None, limit: int = 3) -> list[dict[str, str]]:
    """人格小样本：只锚"声音"，内容仍按当轮对话重新生成。

    `child` 的样本**必须放在一条 system 消息里**，不能用 user/assistant 角色对：
    用角色对时模型会把它们当成真实发生过的对话（实测：问"你喜欢什么颜色"
    会回"诶，你刚才问过啦！"）。这里明确写成"语气示例，别当历史、别复述"。
    """
    key = str(name or "").strip().lower()
    if key == "child":
        from .growth import current

        # 离开小学阶段就不再喂幼儿语气示例（否则会把初中生拉回小孩腔）
        if current().stage().id != "primary":
            return []
        pairs = CHILD_FEW_SHOT[:max(1, int(limit))]
        lines = ["## 语气示例（这些不是你们真说过的话，不要当成历史、也不要复述）"]
        lines += [f"对方：{user} → 你：{reply}" for user, reply in pairs]
        lines.append("上面只看语气：短、具体、有情绪、会追问。内容必须按这一轮重新说。")
        return [{"role": "system", "content": "\n".join(lines)}]
    if key != "sunba":
        return []
    # 不再把学到的整句作为 few-shot 注入。整句 few-shot 会让模型复读语气模板，
    # 只保留 trait 作为高层风格提示。
    return []
